"""Marina month-end accrual batch, preparation and approval only.

No Leave Allocation inserts, no Leave Ledger changes, and no posting API.
Only controllers explicitly labeled below may mutate a batch.
"""
from __future__ import annotations

import hashlib
from decimal import Decimal

import frappe
from frappe import _
from frappe.model.document import Document
from frappe.utils import flt, get_datetime, now_datetime

from marina_custom_apps.marina_leave_management.monthly_preview import (
    get_candidates,
    validate_credit_date,
)

D = Decimal
APPROVABLE = {"Ready for Approval", "Needs Review", "Zero accrual", "Not eligible yet"}
BLOCKERS = {"Calculation error", "No accrual for date"}
BATCH = "Marina Leave Accrual Batch"


def require_hr_manager():
    """HR decision authority. System Manager is an administrator fallback."""
    user = frappe.session.user
    if user != "Administrator" and not set(
        frappe.get_roles(user)
    ).intersection({"HR Manager", "System Manager"}):
        frappe.throw(_("HR Manager or System Manager required"), frappe.PermissionError)


def stable_key(company, credit_date):
    """Stable, unique batch identity for company+month, no company naming collisions."""
    company_hash = hashlib.sha256(company.encode("utf-8")).hexdigest()[:12].upper()
    return f"MLAB-{credit_date:%Y%m%d}-{company_hash}"


def canonical(row):
    """Signed snapshot of material fields used for approval checks."""
    keys = ("employee", "entitlement", "period", "candidate_credit",
            "excluded_days", "status", "notes")
    payload = "|".join(str(row.get(key) or "") for key in keys)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


class MarinaLeaveAccrualBatch(Document):
    def before_insert(self):
        require_hr_manager()
        date = validate_credit_date(self.credit_date)
        if not self.company or not frappe.db.exists("Company", self.company):
            frappe.throw(_("Valid company is required"))
        self.batch_key = stable_key(self.company, date)
        self.status = "Draft"
        self.set("employees", [])
        self.eligible_count = 0
        self.review_count = 0
        self.total_credit = 0
        self.prepared_by = None
        self.prepared_on = None
        self.approved_by = None
        self.approved_on = None
        self.control_note = "No leave allocations will be posted by this batch version."

    def validate(self):
        require_hr_manager()
        date = validate_credit_date(self.credit_date)
        if not self.company:
            frappe.throw(_("Company is required"))
        key = stable_key(self.company, date)
        if self.batch_key != key:
            frappe.throw(_("Company and credit month cannot be changed"))
        if self.is_new():
            if self.status != "Draft" or self.employees:
                frappe.throw(_("New batches must start empty in Draft"))
        elif not getattr(self.flags, "marina_internal_action", False):
            old = self.get_doc_before_save()
            if old:
                # Read-only lifecycle values cannot be changed via REST / imports.
                protected = (
                    "status", "employees", "eligible_count", "review_count",
                    "total_credit", "prepared_by", "prepared_on",
                    "approved_by", "approved_on", "control_note",
                )
                for field in protected:
                    current = self.get(field)
                    previous = old.get(field)
                    if field == "employees":
                        if [x.as_dict() for x in current] != [x.as_dict() for x in previous]:
                            frappe.throw(_("Accrual lines may only be generated by the batch action"))
                    elif current != previous:
                        frappe.throw(_("Batch control fields cannot be edited manually: {0}").format(field))
        if self.status == "Approved" and not getattr(self.flags, "marina_internal_action", False):
            old = self.get_doc_before_save()
            if old and (old.company != self.company or old.credit_date != self.credit_date):
                frappe.throw(_("Approved batches are immutable"))


def _get_locked(name):
    require_hr_manager()
    # Row lock prevents simultaneous generation/approval actions.
    frappe.db.sql("SELECT name FROM `tabMarina Leave Accrual Batch` WHERE name=%s FOR UPDATE", name)
    doc = frappe.get_doc(BATCH, name)
    doc.check_permission("write")
    return doc


def _candidate_rows(doc):
    return get_candidates(
        credit_date=doc.credit_date, company=doc.company, include_exempt=False
    )


def _line_dict(row):
    return {
        "employee": row["employee"],
        "employee_name": row.get("employee_name"),
        "entitlement": row.get("entitlement"),
        "period": row.get("period"),
        "eligible_days": None if row.get("candidate_credit") is None else
                         flt(row.get("candidate_credit"), 6) * 0 + 0,  # populated below
        "excluded_days": flt(row.get("excluded_days") or 0, 6),
        "candidate_credit": flt(row.get("candidate_credit") or 0, 6),
        "status": row["status"],
        "notes": row.get("notes", ""),
        "calculation_signature": canonical(row),
    }


@frappe.whitelist()
def generate_batch(name):
    """Rebuild draft batch from current HRMS data; never post any credit."""
    doc = _get_locked(name)
    if doc.status not in ("Draft", "Calculated"):
        frappe.throw(_("Only draft/calculated batches can be regenerated"))
    rows = _candidate_rows(doc)
    if not rows:
        frappe.throw(_("No eligible employees found for this company/month"))
    if len({x["employee"] for x in rows}) != len(rows):
        frappe.throw(_("Duplicate employee in accrual candidate list"))

    doc.set("employees", [])
    for row in rows:
        line = _line_dict(row)
        # Actual eligible calendar-day count is computed from joining month
        # and excluded days in an upcoming report enhancement. Until then
        # leave this informational field blank, not an invented estimate.
        line["eligible_days"] = None
        doc.append("employees", line)
    doc.eligible_count = sum(
        1 for row in rows if row.get("candidate_credit") and
        row.get("status") in ("Ready for Approval", "Needs Review")
    )
    doc.review_count = sum(1 for row in rows if row["status"] in
                           ("Needs Review", "Calculation error", "No accrual for date"))
    doc.total_credit = flt(sum(
        (D(str(row["candidate_credit"])) for row in rows
         if row.get("candidate_credit") is not None), D("0")
    ), 6)
    doc.status = "Calculated"
    doc.prepared_by = frappe.session.user
    doc.prepared_on = now_datetime()
    doc.approved_by = None
    doc.approved_on = None
    doc.control_note = (
        "Prepared from current HRMS data; no Leave Allocations posted. "
        "Exceptions require explicit confirmation during approval."
    )
    doc.flags.marina_internal_action = True
    doc.save()
    return {"name": doc.name, "status": doc.status,
            "employee_count": len(rows), "review_count": doc.review_count,
            "total_credit": doc.total_credit}


@frappe.whitelist()
def approve_batch(name, confirm_warnings=0):
    """Approve an unchanged candidate snapshot; no HRMS ledger posting."""
    doc = _get_locked(name)
    if doc.status != "Calculated" or not doc.employees:
        frappe.throw(_("Generate a calculated batch before approval"))
    latest = _candidate_rows(doc)
    saved = {x.employee: x for x in doc.employees}
    if len(saved) != len(doc.employees) or len(saved) != len(latest):
        frappe.throw(_("Employee list changed; regenerate the batch"))
    if any(row["status"] in BLOCKERS for row in latest):
        frappe.throw(_("Batch contains calculation errors; cannot approve"))
    if any(row["status"] not in APPROVABLE for row in latest):
        frappe.throw(_("Batch includes unsupported candidate statuses"))
    if any(saved.get(row["employee"]) is None or
           saved[row["employee"]].calculation_signature != canonical(row)
           for row in latest):
        frappe.throw(_("Candidate data changed; regenerate before approval"))
    has_warnings = any(row["status"] == "Needs Review" for row in latest)
    if has_warnings and not int(confirm_warnings):
        frappe.throw(_("Review warnings and explicitly confirm them before approval"))
    doc.status = "Approved"
    doc.approved_by = frappe.session.user
    doc.approved_on = now_datetime()
    doc.control_note = (
        "Approved for future controlled posting design only. "
        "No Leave Allocations or Leave Ledger entries created."
    )
    doc.flags.marina_internal_action = True
    doc.save()
    return {"name": doc.name, "status": doc.status, "posting_enabled": False}
